// A growing pattern: a staircase of bricks (1, 2, 3, ...), tables joined in a row, squares
// of straws, rows of a theatre. Find it for small cases, then for n (Ε΄ Επαναληπτικό 1,
// 1ο πρόβλημα: «Ο Αντρέι φτιάχνει με τουβλάκια μια σκάλα»).
import { extra, fmt, known, people, sought, type Builder, type Family, type Person, type Rng } from '../../lib.ts';
import type { ProblemStep } from '../../../../shared/types.ts';

const tri = (n: number) => (n * (n + 1)) / 2;

// The strategy step, the same for every setting: the wrong options are the typical mistakes.
function plan(b: Builder, r: Rng, mistake: string, small: string) {
  const right = r.chance(0.5) ? 'Λύνω πρώτα ένα πιο απλό πρόβλημα' : 'Αναζητώ ένα μοτίβο στα πρώτα';
  return b.choice('plan', 'Ποια στρατηγική μας βοηθά;', right, ['Εργάζομαι αντίστροφα, από το τέλος', `${mistake} και τελειώνω`],
    'Με λίγα κομμάτια μπορούμε να ζωγραφίσουμε και να μετρήσουμε. Μετά βλέπουμε τι αλλάζει κάθε φορά.');
}

interface Made { title: string; story: string; steps: ProblemStep[] }
type Maker = (r: Rng, b: Builder, p: Person) => Made | null;

// 1 + 2 + 3 + … + n: a staircase of bricks, a pyramid of cans
const staircase: Maker = (r, b, p) => {
  const n = r.int(8, 20);
  const total = tri(n);
  const box = Math.ceil((total + r.int(20, 120)) / 50) * 50;
  const cans = r.chance(0.5);
  const story = cans
    ? r.pick([
      () => `Στο σούπερ μάρκετ στήνουν μια πυραμίδα από κονσέρβες: ${known('1 κονσέρβα στην κορυφή, 2 στην επόμενη σειρά, 3 στην παρακάτω')} και ούτω καθεξής. ${known(`Η κάτω σειρά έχει ${n} κονσέρβες`)}. ${extra(`Κάθε κονσέρβα ζυγίζει ${r.step(300, 500, 50)} γραμμάρια`)}. ${sought('Πόσες κονσέρβες έχει όλη η πυραμίδα')};`,
      () => `${sought('Πόσες κονσέρβες χρειάζονται')} για μια πυραμίδα με ${known(`${n} σειρές`)}, αν ${known('η πάνω σειρά έχει 1 κονσέρβα, η επόμενη 2, η παρακάτω 3')} και ούτω καθεξής; ${p.Nom} τη στήνει στο μαγαζί του θείου ${p.his}, ${extra(`που είναι ανοιχτό ${r.int(8, 12)} ώρες την ημέρα`)}.`,
    ])()
    : r.pick([
      () => `${p.Nom} φτιάχνει με τουβλάκια μια σκάλα. Για το πρώτο σκαλοπάτι χρησιμοποιεί ${known('1 τουβλάκι, για το δεύτερο 2, για το τρίτο 3')} και ούτω καθεξής. ${sought('Πόσα τουβλάκια χρειάζεται')}, για να φτιάξει με τον ίδιο τρόπο μια σκάλα με ${known(`${n} σκαλοπάτια`)}; Έχει ${extra(`ένα κουτί με ${fmt(box)} τουβλάκια`)}.`,
      () => `${p.Nom} έχει ${extra(`${fmt(box)} τουβλάκια`)}. Χτίζει μια σκάλα: ${known('1 τουβλάκι το πρώτο σκαλοπάτι, 2 το δεύτερο, 3 το τρίτο')} και ούτω καθεξής. ${sought('Πόσα τουβλάκια θα χρησιμοποιήσει')} για μια σκάλα με ${known(`${n} σκαλοπάτια`)};`,
    ])();
  const what = cans ? 'κονσέρβες' : 'τουβλάκια';
  const one = (k: number) => cans ? `Πυραμίδα με ${k} σειρές` : `Σκάλα με ${k} σκαλοπάτια`;
  const show = r.chance(0.5);
  const hint = n % 2 === 0
    ? `φτιάχνουμε ζευγάρια: 1 + ${n} = ${n + 1}, 2 + ${n - 1} = ${n + 1}, … Πόσα τέτοια ζευγάρια υπάρχουν;`
    : `φτιάχνουμε ζευγάρια: 1 + ${n - 1} = ${n}, 2 + ${n - 2} = ${n}, … και στο τέλος προσθέτουμε και το ${n}.`;
  const steps: ProblemStep[] = [b.tag(undefined, 'Το «και ούτω καθεξής» λέει ότι ο κανόνας συνεχίζει ίδιος. Ό,τι δεν αλλάζει το πλήθος δεν χρειάζεται.')];
  if (r.chance(0.7)) steps.push(plan(b, r, `Πολλαπλασιάζω ${n} × ${n}`, cans ? 'για λίγες σειρές' : 'για λίγα σκαλοπάτια'));
  steps.push(b.numbers('solve', 'Λύνουμε ένα πιο απλό πρόβλημα και μετά το δικό μας.', [
    { label: show ? `${one(3)}: 1 + 2 + 3 =` : one(3), answer: 6, unit: what },
    { label: show ? `${one(4)}: 6 + 4 =` : one(4), answer: 10, unit: what },
    { label: show ? `${one(5)}: 10 + 5 =` : one(5), answer: 15, unit: what },
    { label: one(n), answer: total, unit: what },
  ], `Κάθε φορά προσθέτουμε όσα έχει ${cans ? 'η καινούργια σειρά' : 'το καινούργιο σκαλοπάτι'}. Για ${cans ? 'τις' : 'τα'} ${n} ${cans ? 'σειρές' : 'σκαλοπάτια'}: ${hint}`));
  steps.push(r.chance(0.5)
    ? b.numbers('check', cans ? `Πώς ελέγχουμε; Η πυραμίδα με ${n} σειρές έχει όσες κονσέρβες η πυραμίδα με ${n - 1} σειρές και ${n} ακόμα.` : `Πώς ελέγχουμε; Η σκάλα με ${n} σκαλοπάτια έχει όσα τουβλάκια η σκάλα με ${n - 1} σκαλοπάτια και ${n} ακόμα.`,
      [{ label: `${fmt(tri(n - 1))} + ${n} =`, answer: total }], `Για ${n - 1}: 1 + 2 + … + ${n - 1} είναι ${fmt(tri(n - 1))}.`)
    : b.choice('check', `Κάποιος απάντησε «${fmt(n * n)}». Τι έκανε λάθος;`,
      `Μέτρησε ${n} σε κάθε ${cans ? 'σειρά' : 'σκαλοπάτι'}`,
      ['Τίποτα, είναι σωστό', `Ξέχασε ${cans ? 'μία σειρά, την πάνω' : 'ένα σκαλοπάτι, το πρώτο'}`],
      `Μόνο ${cans ? 'η κάτω σειρά έχει' : 'το τελευταίο σκαλοπάτι έχει'} ${n}. ${cans ? 'Οι άλλες σειρές έχουν λιγότερες.' : 'Τα άλλα σκαλοπάτια έχουν λιγότερα.'}`));
  return { title: cans ? 'Η πυραμίδα από κονσέρβες' : 'Η σκάλα με τα τουβλάκια', story, steps };
};

// Tables joined in a row (2n + 2) and squares of straws side by side (3n + 1)
const linear: Maker = (r, b, p) => {
  const straws = r.chance(0.5);
  const n = straws ? r.int(10, 50) : r.int(8, 40);
  const per = straws ? 3 : 2;
  const base = straws ? 1 : 2;
  const f = (k: number) => per * k + base;
  const total = f(n);
  let story: string;
  let whatNom = 'καλαμάκια';
  if (straws) {
    story = r.pick([
      () => `${p.Nom} φτιάχνει τετράγωνα με καλαμάκια, το ένα δίπλα στο άλλο, σε μια σειρά. ${known('Για 1 τετράγωνο χρειάζεται 4 καλαμάκια, για 2 τετράγωνα 7 και για 3 τετράγωνα 10')}. ${sought('Πόσα καλαμάκια χρειάζεται')} για ${known(`${n} τετράγωνα`)}; ${extra(`Κάθε καλαμάκι έχει μήκος ${r.int(12, 20)} εκατοστά`)}.`,
      () => `${sought('Πόσα καλαμάκια χρειάζονται')} για ${known(`${n} τετράγωνα`)} στη σειρά; ${p.Nom} ${extra(`αγόρασε ${r.int(2, 4)} πακέτα καλαμάκια`)} και άρχισε: ${known('1 τετράγωνο με 4 καλαμάκια, 2 τετράγωνα με 7, 3 τετράγωνα με 10')}.`,
      () => `Στο μάθημα των Μαθηματικών, ${p.nom} και ${extra(`άλλα ${r.int(18, 24)} παιδιά`)} φτιάχνουν τετράγωνα με καλαμάκια, το ένα δίπλα στο άλλο. ${known('Το 1 τετράγωνο θέλει 4 καλαμάκια, τα 2 τετράγωνα 7 και τα 3 τετράγωνα 10')}. ${sought('Πόσα καλαμάκια θέλουν')} ${known(`${n} τετράγωνα`)};`,
    ])();
  } else {
    const t = r.int(0, 2);
    whatNom = ['παιδιά', 'καρέκλες', 'άτομα'][t];
    story = [
      () => `Για τη γιορτή του σχολείου ενώνουν τετράγωνα τραπέζια σε μια σειρά. ${known('Σε 1 τραπέζι κάθονται 4 παιδιά, σε 2 ενωμένα τραπέζια 6 και σε 3 ενωμένα τραπέζια 8')}. ${sought('Πόσα παιδιά κάθονται')} σε ${known(`${n} ενωμένα τραπέζια`)}; ${extra(`Η γιορτή αρχίζει στις ${r.int(5, 7)} το απόγευμα`)}.`,
      () => `${sought('Πόσες καρέκλες χρειάζονται')} γύρω από ${known(`${n} τετράγωνα τραπέζια`)} ενωμένα σε μια σειρά; ${known('Σε 1 τραπέζι μπαίνουν 4 καρέκλες, σε 2 ενωμένα 6 και σε 3 ενωμένα 8')}. Τα τραπέζια είναι για τη γιορτή της γειτονιάς ${p.gen}, ${extra(`που θα κρατήσει ${r.int(3, 5)} ώρες`)}.`,
      () => `Η ταβέρνα του παππού ${p.gen} έχει ${extra(`${n + r.int(5, 20)} τετράγωνα τραπέζια`)}. Για ένα μεγάλο τραπέζι τα ενώνει σε μια σειρά: ${known('σε 1 τραπέζι κάθονται 4 άτομα, σε 2 ενωμένα 6, σε 3 ενωμένα 8')}. ${sought('Πόσα άτομα κάθονται')} σε ${known(`${n} ενωμένα τραπέζια`)};`,
    ][t]();
  }
  const one = (k: number) => straws ? `Για ${k} τετράγωνα` : `Για ${k} τραπέζια`;
  const show = r.chance(0.5);
  const steps: ProblemStep[] = [b.tag(undefined, 'Χρειαζόμαστε τον κανόνα και για πόσα ρωτάμε. Ό,τι δεν αλλάζει το πλήθος το αφήνουμε.')];
  if (r.chance(0.6)) steps.push(plan(b, r, `Πολλαπλασιάζω ${n} × 4`, straws ? 'για λίγα τετράγωνα' : 'για λίγα τραπέζια'));
  steps.push(b.numbers('solve', 'Βρίσκουμε το μοτίβο και το χρησιμοποιούμε.', [
    { label: straws ? 'Πόσα καλαμάκια προσθέτει κάθε νέο τετράγωνο' : `${whatNom === 'παιδιά' ? 'Πόσα παιδιά' : whatNom === 'άτομα' ? 'Πόσα άτομα' : 'Πόσες καρέκλες'} προσθέτει κάθε νέο τραπέζι`, answer: per },
    { label: show ? `${one(4)}: ${f(3)} + ${per} =` : one(4), answer: f(4), unit: whatNom },
    { label: show ? `${one(n)}: ${per} × ${n} + ${base} =` : one(n), answer: total, unit: whatNom },
  ], straws
    ? `Από 4 σε 7 και από 7 σε 10: κάθε φορά ${per} ακόμα. Το πρώτο τετράγωνο έχει ένα καλαμάκι παραπάνω: ${per} × ${n} + ${base}.`
    : `Από 4 σε 6 και από 6 σε 8: κάθε φορά ${per} ακόμα. Κάθε τραπέζι έχει ${per} θέσεις στα πλάγια και στις δύο άκρες υπάρχει από ${base / 2} ακόμα: ${per} × ${n} + ${base}.`));
  steps.push(r.chance(0.5)
    ? b.numbers('check', `Πώς ελέγχουμε; Δοκιμάζουμε τον κανόνα σε κάτι που ξέρουμε: για 3 ${straws ? 'τετράγωνα' : 'τραπέζια'}.`,
      [{ label: `${per} × 3 + ${base} =`, answer: f(3) }], `Η ιστορία λέει ${f(3)}. Αν βγει το ίδιο, ο κανόνας δουλεύει.`)
    : b.choice('check', `Κάποιος απάντησε «${fmt(4 * n)}». Τι ξέχασε;`,
      straws ? 'Ότι τα διπλανά έχουν κοινό καλαμάκι' : 'Ότι στις ενώσεις χάνονται θέσεις',
      [`Τίποτα, κάθε ${straws ? 'τετράγωνο θέλει 4 καλαμάκια' : 'τραπέζι έχει 4 θέσεις'}`, `Να προσθέσει ${straws ? 'ένα ακόμα τετράγωνο' : 'ένα ακόμα τραπέζι'}`],
      straws ? 'Ζωγράφισε 2 τετράγωνα το ένα δίπλα στο άλλο και μέτρησε τα καλαμάκια.' : 'Ζωγράφισε 2 ενωμένα τραπέζια και μέτρησε τις θέσεις.'));
  return { title: straws ? 'Τα τετράγωνα με τα καλαμάκια' : 'Τα ενωμένα τραπέζια', story, steps };
};

// Rows of an open-air theatre: each row has 2 seats more than the one in front
const theatre: Maker = (r, b, p) => {
  const a = r.int(10, 22);
  const n = r.int(8, 25);
  const rows = n + r.int(3, 12);
  const at = a + 2 * (n - 1);
  const story = r.pick([
    () => `Ένα θέατρο έχει ${known(`στην πρώτη σειρά ${a} θέσεις, στη δεύτερη ${a + 2} και στην τρίτη ${a + 4}`)}, και ούτω καθεξής. ${extra(`Έχει ${rows} σειρές`)}. ${sought('Πόσες θέσεις έχει η σειρά')} ${known(`με τον αριθμό ${n}`)};`,
    () => `${p.Nom} έχει εισιτήριο για ${known(`τη σειρά ${n}`)} ενός αρχαίου θεάτρου, ${extra(`που χτίστηκε πριν από ${fmt(r.step(2_000, 2_400, 100))} χρόνια`)}. ${known(`Η πρώτη σειρά έχει ${a} θέσεις και κάθε επόμενη σειρά 2 θέσεις περισσότερες`)}. ${sought(`Πόσες θέσεις έχει η σειρά ${p.his}`)};`,
    () => `${sought('Πόσες θέσεις έχει η σειρά')} ${known(`${n}`)} ενός θεάτρου, αν ${known(`η σειρά 1 έχει ${a} θέσεις, η σειρά 2 έχει ${a + 2} και η σειρά 3 έχει ${a + 4}`)}; Το θέατρο ${extra(`ανοίγει στις ${r.int(8, 9)} το βράδυ`)}.`,
  ])();
  const show = r.chance(0.5);
  const steps: ProblemStep[] = [b.tag(undefined, 'Χρειαζόμαστε πώς αλλάζουν οι σειρές και ποια σειρά ζητάμε.')];
  if (r.chance(0.6)) steps.push(plan(b, r, `Πολλαπλασιάζω ${a} × ${n}`, 'για τις πρώτες σειρές'));
  steps.push(b.numbers('solve', 'Βρίσκουμε το μοτίβο και το χρησιμοποιούμε.', [
    { label: 'Πόσες θέσεις προστίθενται σε κάθε σειρά', answer: 2 },
    { label: show ? `Σειρά 4: ${a + 4} + 2 =` : 'Σειρά 4', answer: a + 6, unit: 'θέσεις' },
    { label: show ? `Σειρά ${n}: ${a} + 2 × ${n - 1} =` : `Σειρά ${n}`, answer: at, unit: 'θέσεις' },
  ], `Από την πρώτη σειρά ως τη σειρά ${n} ανεβαίνουμε ${n - 1} φορές, και κάθε φορά προστίθενται 2 θέσεις.`));
  steps.push(r.chance(0.5)
    ? b.numbers('check', 'Πώς ελέγχουμε; Δοκιμάζουμε τον κανόνα στη σειρά 3, που την ξέρουμε.', [{ label: `${a} + 2 × 2 =`, answer: a + 4 }],
      'Από την πρώτη ως την τρίτη σειρά ανεβαίνουμε 2 φορές.')
    : b.choice('check', `Κάποιος απάντησε «${fmt(a + 2 * n)}». Τι έκανε λάθος;`, `Μέτρησε ${n} φορές το 2, όχι ${n - 1}`,
      ['Τίποτα, είναι σωστό', `Έπρεπε να πολλαπλασιάσει ${a} × ${n}`],
      'Η πρώτη σειρά έχει ήδη τις θέσεις της. Οι 2 θέσεις προστίθενται από τη δεύτερη σειρά και μετά.'));
  return { title: 'Οι σειρές του θεάτρου', story, steps };
};

const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

export const patternSum: Family = {
  id: 'pattern-sum',
  grade: 5,
  unit: 1,
  source: 'Μαθηματικά Ε΄, Επαναληπτικό 1, 1ο πρόβλημα (η σκάλα με τα τουβλάκια)',
  make(r, b) {
    const [p] = people(r, 1);
    const m = r.pick([staircase, staircase, linear, linear, theatre]);
    return m(r, b, p);
  },
};

test('prices: each with its own item, in every phrasing', () => {
  reads('Στο κατάστημα παιχνιδιών ξόδεψε 3 ευρώ για ένα γιογιό και 21 ευρώ για ένα επιτραπέζιο παιχνίδι.', 'γιογιό 3', 'επιτραπέζιο 21');
  passes('Στο κατάστημα παιχνιδιών ξόδεψε 3 ευρώ για ένα γιογιό και 21 ευρώ για ένα επιτραπέζιο παιχνίδι.');
  fails('Στο κατάστημα παιχνιδιών ξόδεψε 21 ευρώ για ένα γιογιό και 3 ευρώ για ένα επιτραπέζιο παιχνίδι.', /επιτραπέζιο/);
  reads('Ένα παζλ κοστίζει 400 ευρώ.', 'παζλ 400');
  fails('Ένα παζλ κοστίζει 400 ευρώ.', /400 € for παζλ/);
  fails('Ο Νίκος αγοράζει ένα επιτραπέζιο παιχνίδι των 3 €.', /3 € for επιτραπέζιο/);
  fails('Ο Αλέξης ξόδεψε δύο ευρώ για ένα ποδήλατο.', /2 € for ποδήλατο/);
  reads('Ο Αλέξης ξόδεψε δέκα ευρώ για ένα παζλ.', 'παζλ 10');
  passes('Ο Αλέξης ξόδεψε δέκα ευρώ για ένα παζλ.');
  fails('Έβγαλε 60 ευρώ για να αγοράσει ένα βιβλίο.', /60 € for βιβλίο/);
  reads('Αγόρασε 3 κιλά πατάτες, που έκαναν 2 ευρώ το κιλό.', 'πατάτες 2');
  fails('Αγόρασε 3 κιλά πατάτες, που έκαναν 20 ευρώ το κιλό.', /20 € for πατάτες/);
  reads('Η βενζίνη θα κοστίσει 80 €, τα διόδια 12 € για κάθε διαδρομή, στο πήγαινε και στο έλα.', 'βενζίνη 80', 'διόδια 12');
  passes('Η βενζίνη θα κοστίσει 80 €, τα διόδια 12 € για κάθε διαδρομή, στο πήγαινε και στο έλα.');
});

test('prices: «αγόρασε X με N ευρώ», past or present, accent or none', () => {
  const fair = 'Στο λούνα παρκ αγόρασε ένα λούτρινο αρκουδάκι με 12 ευρώ και ένα εισιτήριο για τη ρόδα με 4 ευρώ.';
  reads(fair, 'λούτρινο αρκουδάκι 12', 'ρόδα 4');
  passes(fair);
  fails('Στο λούνα παρκ αγόρασε ένα λούτρινο αρκουδάκι με 500 ευρώ.', /500 € for λούτρινο αρκουδάκι/);
  fails('Στο λούνα παρκ αγοράζει ένα λούτρινο αρκουδάκι με 500 ευρώ.', /500 € for λούτρινο αρκουδάκι/);
  fails('Στο λούνα παρκ αγόρασε ένα λούτρινο αρκουδάκι με 12 ευρώ και ένα εισιτήριο για τη ρόδα με 40 ευρώ.', /40 € for ρόδα/);
});

test('prices: «θέλει να πάρει N € για X», and «για X» after a price is X\'s, not the item before', () => {
  const club = 'Ο προπονητής θέλει να πάρει 685 € για το λεωφορείο για τους αγώνες και στρώματα γυμναστικής αξίας 330 €.';
  reads(club, 'λεωφορείο για τους αγώνες 685', 'στρώματα γυμναστικής 330');
  passes(club);
  fails('Ο προπονητής θέλει να πάρει 5 € για το λεωφορείο για τους αγώνες.', /5 € for λεωφορείο/);
  const three = 'Ο προπονητής θέλει να πάρει στολές για την ομάδα αξίας 564 €, ένα καινούργιο καλάθι μπάσκετ των 935 € και 730 € για το λεωφορείο για τους αγώνες.';
  reads(three, 'στολές για την ομάδα 564', 'καλάθι μπάσκετ 935', 'λεωφορείο για τους αγώνες 730');
  passes(three);
  // «για όλη την ημέρα» is how long, not an item
  reads('Η είσοδος κοστίζει 30 € το άτομο και το πάρκινγκ 9 € για όλη την ημέρα.', 'είσοδος 30', 'πάρκινγκ 9');
  // «Πυθαγόρας» is no «αγορ-»
  reads('Ο Πυθαγόρας βγήκε βόλτα με 40 ευρώ στην τσέπη.');
  // An item the table doesn't know, after «για»: no item, never the one before
  fails('Ο προπονητής θέλει να πάρει ένα καινούργιο καλάθι μπάσκετ των 935 € και 730 € για τη νέα κερκίδα.', /no item.*730/);
});

test('prices: a pack is divided by its count, a total by the count in front', () => {
  reads('Το κατάστημα Α πουλά πακέτο με 6 χυμούς για 4 € και το κατάστημα Β πακέτο με 10 χυμούς για 6 €.', 'χυμούς 4/6', 'χυμούς 6/10');
  passes('Το κατάστημα Α πουλά πακέτο με 6 χυμούς για 4 € και το κατάστημα Β πακέτο με 10 χυμούς για 6 €.');
  fails('Το κατάστημα Α πουλά πακέτο με 6 χυμούς για 60 €.', /10 € for χυμ/);
  reads('Στο βιβλιοπωλείο της γειτονιάς τα πέντε τετράδια κοστίζουν 8 ευρώ.', 'τετράδια 8/5');
  passes('Στο βιβλιοπωλείο της γειτονιάς τα πέντε τετράδια κοστίζουν 8 ευρώ.');
  fails('Στο βιβλιοπωλείο της γειτονιάς τα πέντε τετράδια κοστίζουν 80 ευρώ.', /16 € for τετράδι/);
  reads('Ο Μιχάλης αγόρασε 4 θήκες με 6 αυγά, στα 2 ευρώ την καθεμία.', 'αυγά 2/6');
  passes('Ο Μιχάλης αγόρασε 4 θήκες με 6 αυγά, στα 2 ευρώ την καθεμία.');
});


// The story-check's rules on single stories (#50 part 5b), run with Node 24 alone:
//   node --test tools/problem-gen/story-check.test.ts
// Each case is a story as a child reads it; the audit runs the same check on every pool.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import type { ProblemExercise } from '../../shared/types.ts';
import { checkStory } from './story-check.ts';

const ex = (story: string) => ({ id: 't', type: 'problem', title: 't', category: 'Μαθηματικά', story, steps: [] }) as unknown as ProblemExercise;
const passes = (story: string) => assert.deepEqual(checkStory(ex(story)), [], story);
const fails = (story: string, like: RegExp) => {
  const got = checkStory(ex(story));
  assert.ok(got.some(m => like.test(m)), `expected ${like} for «${story}», got ${JSON.stringify(got)}`);
};

test('relatives and friends are people', () => {
  passes('Η γιαγιά πήγε στη λαϊκή με 50 ευρώ. Αγόρασε 3 κιλά πατάτες, που έκαναν 2 ευρώ το κιλό. Πόσα ευρώ της έμειναν;');
  passes('Ο μπαμπάς πήγε στη λαϊκή με 40 ευρώ. Αγόρασε ένα καρπούζι για 6 ευρώ. Πόσα ευρώ του έμειναν;');
  fails('Η γιαγιά πήγε στη λαϊκή με 50 ευρώ. Η γιαγιά αγόρασε ένα καρπούζι για 6 ευρώ.', /open with «Η γιαγιά»/);
});

test('the worst case: a question with no subject right after someone else\'s sentence', () => {
  fails('Η Μαρίνα έχει 20 ευρώ. Η γιαγιά της έδωσε 10 ευρώ. Πόσα ευρώ έχει τώρα;', /names no one.*γιαγιά/);
  fails('Ο Νίκος έχει 10 κάρτες. Η Άννα έχει 6 κάρτες. Πόσες κάρτες είχε στην αρχή;', /names no one/);
  fails('Η Σοφία έχει στο πορτοφόλι της 20 ευρώ. Αγοράζει 3 τοστ, που κοστίζουν 3 ευρώ το καθένα. Η αδερφή της είναι 7 χρονών. Πόσα ευρώ θα της μείνουν;', /reads as about η αδερφή/);
  passes('Η Σοφία έχει στο πορτοφόλι της 20 ευρώ. Η αδερφή της είναι 7 χρονών. Αγοράζει 3 τοστ, που κοστίζουν 3 ευρώ το καθένα. Πόσα ευρώ θα μείνουν στη Σοφία;');
  fails('Στην κασετίνα του Πυθαγόρα υπάρχουν 3 νομίσματα των 20 λεπτών. Η φίλη του έχει 12 νομίσματα. Πόσα λεπτά έχει;', /reads as about η φίλη/);
  passes('Στην κασετίνα του Πυθαγόρα υπάρχουν 3 νομίσματα των 20 λεπτών. Η φίλη του έχει 12 νομίσματα. Πόσα λεπτά έχει ο Πυθαγόρας;');
});

test('questions that pass: their own subject, a plural verb, a verbless follow-up', () => {
  passes('Η Ζωή και ο Πέτρος κάνουν βόλτα στο λούνα παρκ. Ο Πέτρος κάνει 2 γύρους. Η Ζωή κάνει 3 γύρους. Πόσες καμπίνες έχει η ρόδα;');
  passes('Ο Νίκος έχει 10 κάρτες. Η Άννα έχει 6 κάρτες. Πόσες κάρτες έχουν και οι δύο μαζί;');
  passes('Η Χαρά και ο Νίκος έχουν μαζέψει μαζί 363 €. Ο Νίκος έχει 51 € λιγότερα από τη Χαρά. Πόσα € έχει ο καθένας;');
  passes('Ο Αλέξης πλήρωσε 9 ευρώ. Η Ζωή πλήρωσε 7 ευρώ. Ποιο παιδί πλήρωσε λιγότερα; Πόσα ευρώ λιγότερα;');
  passes('Ο Φώτης κάθεται δίπλα στον Στέλιο. Ο Στέλιος κάθεται απέναντι από τη Ζωή. Πόσα παιδιά είναι στον κύκλο;');
});

test('a neuter phrase is the question\'s subject only where it can\'t be the object', () => {
  passes('Η Ζωή κάθεται στο αλογάκι 3. Ο Θοδωρής κάθεται στο αλογάκι 9. Πόσα αλογάκια έχει το καρουζέλ;');
  passes('Η Ζωή αγόρασε ένα κουδουνάκι. Ο Θοδωρής αγόρασε ένα καλαθάκι. Πόσα € κοστίζει το κουδουνάκι;');
  fails('Η Ζωή έχει ένα δοχείο. Ο Θοδωρής φέρνει νερό. Πόσες φορές θα γεμίσει το δοχείο;', /names no one/);
});

test('«Έχει δίκιο;» after three children names the one who claims', () => {
  const intro = 'Ο Μιχάλης κάνει έναν γύρο σε 4 λεπτά και η Σοφία σε 10. Η Άννα λέει ότι αυτό θα ξαναγίνει σε 40 λεπτά, γιατί 4 × 10 = 40.';
  fails(`${intro} Έχει δίκιο;`, /names no one/);
  passes(`${intro} Έχει δίκιο η Άννα;`);
});

test('«Αναρωτιέται»: whoever wonders is clear', () => {
  passes('Η Ζωή ξόδεψε 12 ευρώ για ένα παζλ. Τώρα έχει 28 ευρώ. Αναρωτιέται πόσα ευρώ είχε στην αρχή.');
  passes('Η Άννα πήρε 5 κάρτες από τον Νίκο. Ο Νίκος αναρωτιέται πόσες κάρτες είχε στην αρχή.');
  fails('Η Άννα πήρε 5 κάρτες από τον Νίκο. Αναρωτιέται πόσες κάρτες είχε στην αρχή.', /αναρωτιέται/i);
});

test('time: «Νωρίτερα» after «Τώρα» tells what came before', () => {
  passes('Τώρα η Κατερίνα έχει 115 αυτοκόλλητα. Νωρίτερα αγόρασε άλλα 39 αυτοκόλλητα. Πόσα αυτοκόλλητα είχε πριν;');
  fails('Τώρα η Κατερίνα έχει 115 αυτοκόλλητα. Μετά αγόρασε άλλα 39 αυτοκόλλητα. Πόσα αυτοκόλλητα έχει;', /a change after «Τώρα/);
});

test('the same genitive in two sentences in a row', () => {
  fails('Στο άλμπουμ του Στέλιου υπήρχαν 89 αυτοκόλλητα. Το άλμπουμ του Στέλιου έχει 40 σελίδες. Πόσα αυτοκόλλητα έχει;', /άλμπουμ του Στέλιου/);
  passes('Στο άλμπουμ του Στέλιου υπήρχαν 89 αυτοκόλλητα. Το άλμπουμ έχει 40 σελίδες. Πόσα αυτοκόλλητα έχει;');
  // A question and its answer: not two told sentences
  passes('Πόσα κουτάκια μάζεψε το σχολείο του Γιώργου; Το σχολείο του Γιώργου μάζεψε 7.542 κουτάκια.');
});

test('prices: each with its own item, in every phrasing', () => {
  passes('Στο κατάστημα παιχνιδιών ξόδεψε 3 ευρώ για ένα γιογιό και 21 ευρώ για ένα επιτραπέζιο παιχνίδι.');
  fails('Στο κατάστημα παιχνιδιών ξόδεψε 21 ευρώ για ένα γιογιό και 3 ευρώ για ένα επιτραπέζιο παιχνίδι.', /επιτραπέζιο/);
  fails('Ένα παζλ κοστίζει 400 ευρώ.', /400 € for παζλ/);
  fails('Ο Νίκος αγοράζει ένα επιτραπέζιο παιχνίδι των 3 €.', /3 € for επιτραπέζιο/);
  fails('Ο Αλέξης ξόδεψε δύο ευρώ για ένα ποδήλατο.', /2 € for ποδήλατο/);
  passes('Ο Αλέξης ξόδεψε δέκα ευρώ για ένα παζλ.');
  fails('Έβγαλε 60 ευρώ για να αγοράσει ένα βιβλίο.', /60 € for βιβλίο/);
  fails('Αγόρασε 3 κιλά πατάτες, που έκαναν 20 ευρώ το κιλό.', /20 € for πατάτες/);
  passes('Στο λούνα παρκ αγόρασε ένα λούτρινο αρκουδάκι με 12 ευρώ και ένα εισιτήριο για τη ρόδα με 4 ευρώ.');
  passes('Η βενζίνη θα κοστίσει 80 €, τα διόδια 12 € για κάθε διαδρομή, στο πήγαινε και στο έλα.');
});

test('prices: a pack is divided by its count, a total by the count in front', () => {
  passes('Το κατάστημα Α πουλά πακέτο με 6 χυμούς για 4 € και το κατάστημα Β πακέτο με 10 χυμούς για 6 €.');
  fails('Το κατάστημα Α πουλά πακέτο με 6 χυμούς για 60 €.', /10 € for χυμ/);
  passes('Στο βιβλιοπωλείο της γειτονιάς τα πέντε τετράδια κοστίζουν 8 ευρώ.');
  fails('Στο βιβλιοπωλείο της γειτονιάς τα πέντε τετράδια κοστίζουν 80 ευρώ.', /16 € for τετράδι/);
  passes('Ο Μιχάλης αγόρασε 4 θήκες με 6 αυγά, στα 2 ευρώ την καθεμία.');
});

test('prices: not a price, and a price with no item', () => {
  passes('Η Μυρτώ βγήκε βόλτα με 20 ευρώ στην τσέπη.');
  passes('Η οικογένεια του Νίκου έχει κρατήσει 1.500 € για τις καλοκαιρινές διακοπές.');
  passes('Το εισιτήριο του ζωολογικού κήπου κοστίζει 12 € για τους ενήλικες και για τα παιδιά 4 € λιγότερα.');
  fails('Στο βιβλιοπωλείο κοστίζει 9 ευρώ.', /no item/);
  fails('Το καθένα κοστίζει 300 €.', /no item/);
});

test('prices: cents, notes and coins', () => {
  passes('Θέλει να αγοράσει ένα αυτοκόλλητο που κοστίζει 40 λεπτά.');
  passes('Ο Θοδωρής αγόρασε ένα περιοδικό με κόμικ που κόστιζε 2 ευρώ και 50 λεπτά.');
  fails('Ο Θοδωρής αγόρασε ένα περιοδικό με κόμικ που κόστιζε 90 ευρώ και 50 λεπτά.', /for περιοδικό/);
  passes('Πληρώνει με ένα χαρτονόμισμα των 50 ευρώ.');
  fails('Πληρώνει με ένα χαρτονόμισμα των 30 ευρώ.', /note of 30/);
  fails('Στον κουμπαρά της υπάρχουν 40 κέρματα των 30 λεπτών.', /coin of 30/);
  passes('Στον κουμπαρά του Πυθαγόρα υπάρχουν 64 κέρματα των 2 €.');
});

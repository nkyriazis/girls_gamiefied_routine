// The story-check's rules on single stories (#50 part 5b), run with Node 24 alone:
//   node --test tools/problem-gen/story-check.test.ts
// Each case is a story as a child reads it; the audit runs the same check on every pool.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import type { ProblemExercise } from '../../shared/types.ts';
import { checkStory, readPrices } from './story-check.ts';

const ex = (story: string) => ({ id: 't', type: 'problem', title: 't', category: 'Μαθηματικά', story, steps: [] }) as unknown as ProblemExercise;
const passes = (story: string) => assert.deepEqual(checkStory(ex(story)), [], story);
const fails = (story: string, like: RegExp) => {
  const got = checkStory(ex(story));
  assert.ok(got.some(m => like.test(m)), `expected ${like} for «${story}», got ${JSON.stringify(got)}`);
};
/** The prices the reader finds, as «item amount» (or «item amount/count» for a pack): a story that
 *  passes proves nothing about a price unless the price was read. */
const reads = (story: string, ...want: string[]) => assert.deepEqual(
  readPrices(story).map(p => 'note' in p ? `note: ${p.note}` : `${p.item} ${p.amount}${p.per > 1 ? `/${p.per}` : ''}`), want, story);

test('relatives and friends are people', () => {
  passes('Η γιαγιά πήγε στη λαϊκή με 50 ευρώ. Αγόρασε 3 κιλά πατάτες, που έκαναν 2 ευρώ το κιλό. Πόσα ευρώ της έμειναν;');
  passes('Ο μπαμπάς πήγε στη λαϊκή με 40 ευρώ. Αγόρασε ένα καρπούζι για 6 ευρώ. Πόσα ευρώ του έμειναν;');
  fails('Η γιαγιά πήγε στη λαϊκή με 50 ευρώ. Η γιαγιά αγόρασε ένα καρπούζι για 6 ευρώ.', /open with «Η γιαγιά»/);
});

test('the worst case: a question with no subject right after someone else\'s sentence', () => {
  fails('Η Μαρίνα έχει 20 ευρώ. Η γιαγιά της έδωσε 10 ευρώ. Πόσα ευρώ έχει τώρα;', /names no one.*γιαγιά/);
  fails('Ο Νίκος έχει 10 κάρτες. Η Άννα έχει 6 κάρτες. Πόσες κάρτες είχε στην αρχή;', /names no one/);
  fails('Η Σοφία έχει στο πορτοφόλι της 20 ευρώ. Αγοράζει 3 τοστ, που κοστίζουν 3 ευρώ το καθένα. Η αδερφή της είναι 7 χρονών. Πόσα ευρώ θα της μείνουν;', /reads as about η αδερφή/);
  passes('Η Σοφία έχει στο πορτοφόλι της 20 ευρώ. Η αδερφή της είναι 7 χρονών. Αγοράζει 3 τοστ, που κοστίζουν 3 ευρώ το καθένα. Πόσα ευρώ θα μείνουν στη Σοφία;');
  fails('Στην κασετίνα του Πυθαγόρα υπάρχουν 3 νομίσματα των 20 λεπτών. Η φίλη του έχει 12 νομίσματα. Πόσα λεπτά έχει;', /reads as about η φίλη/);
  passes('Στην κασετίνα του Πυθαγόρα υπάρχουν 3 νομίσματα των 20 λεπτών. Η φίλη του έχει 12 νομίσματα. Πόσα λεπτά έχει ο Πυθαγόρας;');
});

test('the worst case counts the grown-ups at work too: a driver, a teacher, a coach', () => {
  fails('Η Σοφία έχει 20 ευρώ. Η δασκάλα της έχει 25 μαθητές. Πόσα ευρώ έχει;', /reads as about η δασκάλα/);
  // No child in the story: the driver's sentence is noise (e5-gen-distance-time-003)
  const truck = 'Ένα φορτηγό μεταφέρει φρούτα από τον κάμπο σε μια μεγάλη αγορά. Το φορτηγό διανύει πρώτα [70 χιλιόμετρα κάθε ώρα|known] [για 3 ώρες|known] και μετά, σε πιο δύσκολο δρόμο, [40 χιλιόμετρα κάθε ώρα|known] [για 2 ώρες|known]. Ο οδηγός κάνει αυτή τη δουλειά [19 χρόνια|extra].';
  fails(`${truck} [Πόσα χιλιόμετρα διάνυσε συνολικά|sought];`, /reads as about ο οδηγός/);
  passes(`${truck} [Πόσα χιλιόμετρα διάνυσε συνολικά το φορτηγό|sought];`);
  passes('Όλη η διαδρομή είναι [420 χιλιόμετρα|known]. Το φορτηγό διανύει [70 χιλιόμετρα κάθε ώρα|known]. Ο οδηγός κάνει αυτή τη δουλειά [19 χρόνια|extra]. [Σε πόσες ώρες θα φτάσει το φορτηγό|sought];');
  // The grown-up who does what is asked (e5-gen-arrange-rows)
  passes('Από το σχολείο της Σοφίας θα πάνε στον κινηματογράφο [35 μαθητές|known] και [4 εκπαιδευτικοί|known]. Ο κύριος Αλέξης, ο υπεύθυνος της εκδρομής, θα πληρώσει [με ένα χαρτονόμισμα των 200 €|known]. [Πόσα ρέστα θα πάρει|sought];');
  passes('Στη γυμναστική επίδειξη του σχολείου, [που θα κρατήσει 37 λεπτά|extra], θα πάρουν μέρος [48 μαθητές|known]. Ο γυμναστής θέλει να τους βάλει σε ίσες σειρές, [με τουλάχιστον 2 σειρές και τουλάχιστον 2 μαθητές σε κάθε σειρά|known]. [Με πόσους διαφορετικούς τρόπους μπορεί να το κάνει|sought];');
  fails('Ο Νίκος παίζει μπάσκετ 3 φορές την εβδομάδα. Ο προπονητής του έχει 12 μπάλες. Πόσες ώρες παίζει κάθε εβδομάδα;', /reads as about ο προπονητής/);
  // The story's own grown-up: the one its first sentence is about
  passes('Ο φούρναρης έφτιαξε 200 κουλούρια το πρωί. Πούλησε τα 150 ως το μεσημέρι. Πόσα κουλούρια έχει ακόμα;');
  passes('Ο φούρναρης έφτιαξε 200 κουλούρια το πρωί. Ο φούρναρης δουλεύει εδώ 20 χρόνια. Πόσα κουλούρια φτιάχνει σε 3 ημέρες;');
});


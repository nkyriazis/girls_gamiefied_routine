/** «Κύκλωσε τον χρόνο του ρήματος «κυλούσε».» under the sentence it is in. */
const tense = (sentence: string, verb: string, right: string, wrong: string[]) =>
  choose('Οι χρόνοι του ρήματος', `Κύκλωσε τον χρόνο του ρήματος «${verb}».`, right, wrong, sentence);
/** «Κύκλωσε την έγκλιση του ρήματος «πάρε».» under the sentence it is in. */
const mood = (sentence: string, verb: string, right: string, wrong: string[]) =>
  choose('Οι εγκλίσεις του ρήματος', `Κύκλωσε την έγκλιση του ρήματος «${verb}».`, right, wrong, sentence);
const adverb = (sentence: string, word: string, right: string, wrong: string[]) =>
  choose('Επιρρήματα: πότε, πού, πώς;', `Τι φανερώνει το επίρρημα «${word}» στην πρόταση;`, right, wrong, sentence);
const define = (means: string, right: string, wrong: string[]) =>
  choose('Λέξεις και ορισμοί', `Κύκλωσε τη λέξη που ταιριάζει στον ορισμό: «${means}».`, right, wrong);


// Speak to the child in the imperative («Κύκλωσε», «Συμπλήρωσε», «Βάλε»), the same to every child: no
// word of check-gender's list, anywhere in the item. One gap per fill-blank, a whole word, in a sentence
// that fits one line with its gap (check.ts FILL_LINE_MAX). Only families whose key the audit can prove:
// no δε(ν)/μη(ν) where the subjunctive could follow too, no masculine genitive of an -ης adjective (the
// everyday «του δημοφιλή» would be a right answer offered as wrong), no definitions too close to tell
// apart (αφετηρία, σταθμός, στάση, τέρμα), and proverbs completed, never explained.

